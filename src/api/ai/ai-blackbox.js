module.exports = function (app) {
  const axios = require('axios')

  const ORIGIN = 'https://app.blackbox.ai'
  const UA =
    'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/149.0.0.0 Safari/537.36 Edg/149.0.0.0'

  const FALLBACK_VALIDATED =
    'a38f5889-8fef-46d4-8ede-bf4668b6a9bb'

  const ANCHOR =
    /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})";function detectVscode/

  const WRAP_SYSTEM =
    'Wrap your entire reply between <answer> and </answer> tags. Write nothing outside these tags.'

  const OPEN_TAG =
    /^(?:<answer>|answer>|nswer>|swer>|wer>|er>|r>|>)\s*/

  let cachedValidated = FALLBACK_VALIDATED

  function randomId(len = 7) {
    const chars =
      'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'

    let str = ''

    for (let i = 0; i < len; i++) {
      str += chars[Math.floor(Math.random() * chars.length)]
    }

    return str
  }

  function isRejected(text = '') {
    return /Generated by BLACKBOX\.AI|not upgraded your account/i.test(text)
  }

  function parseAnswer(raw = '') {
    const thinks = []

    let body = raw.replace(
      /<think>([\s\S]*?)<\/think>/g,
      (_, think) => {
        thinks.push(think.trim())
        return ''
      }
    )

    const end = body.indexOf('</answer>')

    if (end !== -1) {
      body = body
        .slice(0, end)
        .trimStart()
        .replace(OPEN_TAG, '')
    }

    return {
      text: body.trim(),
      think: thinks.join('\n\n').trim() || null
    }
  }

  async function fetchValidated() {
    try {
      const { data: html } = await axios.get(
        `${ORIGIN}/`,
        {
          headers: {
            'user-agent': UA
          },
          timeout: 15000
        }
      )

      const chunks = [
        ...new Set(
          [...html.matchAll(/\/_next\/static\/[^"]+\.js/g)]
            .map(v => v[0])
        )
      ]

      for (const chunk of chunks) {
        try {
          const { data: js } = await axios.get(
            `${ORIGIN}${chunk}`,
            {
              headers: {
                'user-agent': UA
              },
              timeout: 15000
            }
          )

          const match = js.match(ANCHOR)

          if (match?.[1]) {
            return match[1]
          }
        } catch {}
      }

      return null
    } catch {
      return null
    }
  }

  function buildPayload(messages, validated, options = {}) {
    const {
      webSearch = false,
      agent = 'VscodeAgent',
      maxTokens = 1024
    } = options

    return {
      messages,
      id: messages[messages.length - 1].id,
      userSelectedAgent: agent,
      userSelectedModel: null,
      maxTokens,
      validated,
      clickedForceWebSearch: webSearch,
      webSearchModeOption: {
        autoMode: !webSearch,
        webMode: webSearch,
        offlineMode: false
      },
      codeModelMode: true,
      isPremium: false
    }
  }

  async function request(payload) {
    const { data } = await axios.post(
      `${ORIGIN}/api/chat`,
      payload,
      {
        headers: {
          'content-type': 'application/json',
          'origin': ORIGIN,
          'referer': `${ORIGIN}/chat`,
          'user-agent': UA
        },
        timeout: 60000
      }
    )

    return data
  }

  async function blackboxChat(prompt, options = {}) {
    const history =
      Array.isArray(options.history)
        ? options.history
        : []

    const userMsg = {
      id: randomId(),
      role: 'user',
      content: String(prompt)
    }

    const messages = [
      {
        id: randomId(),
        role: 'system',
        content: WRAP_SYSTEM
      },
      ...history,
      userMsg
    ]

    let raw = await request(
      buildPayload(
        messages,
        cachedValidated,
        options
      )
    )

    if (isRejected(raw)) {
      const fresh = await fetchValidated()

      if (
        fresh &&
        fresh !== cachedValidated
      ) {
        cachedValidated = fresh

        raw = await request(
          buildPayload(
            messages,
            cachedValidated,
            options
          )
        )
      }
    }

    if (isRejected(raw)) {
      return {
        ok: false,
        error: raw.trim(),
        validated: cachedValidated
      }
    }

    const parsed = parseAnswer(raw)

    return {
      ok: true,
      text: parsed.text,
      think: parsed.think,
      validated: cachedValidated,
      history: [
        ...history,
        userMsg,
        {
          id: randomId(),
          role: 'assistant',
          content: parsed.text
        }
      ]
    }
  }

  app.get('/ai/blackbox', async (req, res) => {
    try {
      const {
        prompt,
        webSearch
      } = req.query

      if (!prompt) {
        return res.json({
          status: false,
          error: 'Falta parametro ?prompt='
        })
      }

      const result =
        await blackboxChat(prompt, {
          webSearch:
            String(webSearch) === 'true'
        })

      res.json({
        status: true,
        result
      })

    } catch (err) {
      res.json({
        status: false,
        error:
          err.response?.data ||
          err.message
      })
    }
  })
}